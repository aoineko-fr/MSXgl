// Generate MSXgl Arkos replayers from Arkos Tracker Z80 sources
//
// Usage: node generate.js [player...]   (no argument = all players)
//─────────────────────────────────────────────────────────────────────────────
const fs = require('fs');
const path = require('path');
const cp = require('child_process');

// Players list: name (used for <name>_profile.asm and <name>_player.asm) and labels prefix (null = keep Arkos one)
const PLAYERS =
[
	{ name: 'akg',       prefix: null },
	{ name: 'akm',       prefix: null },
	{ name: 'aky',       prefix: null },
	{ name: 'aky_6ch',   prefix: 'AKY_6CH_' },
	{ name: 'aky_darky', prefix: 'AKY_DARKY_' },
	{ name: 'aky_9ch',   prefix: 'AKY_9CH_' },
	{ name: 'aky_12ch',  prefix: 'AKY_12CH_' },
];

const DIR   = __dirname;
const TOOLS = path.join(DIR, '../../../tools/audio/arkos');
const OUT   = path.join(DIR, 'out');

//-----------------------------------------------------------------------------
function run(exe, args)
{
	try { cp.execFileSync(path.join(TOOLS, exe), args, { cwd: DIR, stdio: 'pipe' }); }
	catch (e) { throw new Error(`${exe} failed:\n${e.stdout}${e.stderr}`); }
}

//-----------------------------------------------------------------------------
function generate(player)
{
	const name = player.name;
	const bin = path.join(OUT, `${name}_player.bin`);
	const sym = path.join(OUT, `${name}_player.sym`);
	const dis = path.join(OUT, `${name}_player.asm`);
	for (const f of [bin, sym, dis])
		fs.rmSync(f, { force: true });

	// Assemble
	run('rasm_win64.exe', [`${name}_profile.asm`, '-o', `out/${name}_player`, '-s', '-sl', '-sq', '-xr', '-m']);
	if (!fs.existsSync(bin))
		throw new Error('rasm did not generate the binary file');

	// Disassemble
	run('Disark.exe', [bin, dis, '--symbolFile', sym, '--undocumentedOpcodesToBytes', '--src16bitsValuesInHex', '--src8bitsValuesInHex', '--sourceProfile', 'sdcc']);
	if (!fs.existsSync(dis))
		throw new Error('Disark did not generate the source file');

	// Formatting and MSXgl adaptation
	let src = fs.readFileSync(dis, 'utf8');
	src = src.replaceAll(': ', ':\n\t');        // One label/instruction per line
	src = src.replaceAll("af'", "af' ;'");      // Close the quote for the C preprocessor
	if (player.prefix)                          // Unique labels for each replayer
		src = src.replaceAll('AKY_', player.prefix);
	src = src.replace(/^(PLY_\w+ = )(0x[fF][0-9a-fA-F]{3})[ \t\r]*$/gm, '$1ARKOS_ADDR($2)'); // RAM buffer can be relocated

	const date = new Date().toISOString().replace('T', ' ').slice(0, 19);
	const header =
	[
		"; ____________________________",
		"; ██▀▀█▀▀██▀▀▀▀▀▀▀█▀▀█        │   ▄▄       ▄▄",
		"; ██  ▀  █▄  ▀██▄ ▀ ▄█ ▄▀▀ █  │  ██▄█ ██▄▀ ██▄▀ ▄█▀▄  ██▀",
		"; █  █ █  ▀▀  ▄█  █  █ ▀▄█ █▄ │  ██ █ ██   ██ █ ▀█▄▀ ▄██",
		"; ▀▀▀▀▀▀▀▀▀▀▀▀▀▀▀▀▀▀▀▀────────┘",
		";  by Guillaume 'Aoineko' Blanchard under CC BY-SA license",
		";==============================================================================",
		`; Autogenerated Arkos ${name.toUpperCase()} player for MSX-GL library`,
		`;  on ${date} (UTC)`,
		";",
		"; Arkos Tracker and the Z80 players are coded and designed",
		";  by Julien Névo (aka Targhan/Arkos) under MIT License.",
		";==============================================================================",
		"",
	].join('\n');

	fs.writeFileSync(path.join(DIR, `${name}_player.asm`), (header + src).replace(/\r?\n/g, '\r\n'));
}

//-----------------------------------------------------------------------------
const args = process.argv.slice(2).map(a => a.toLowerCase());
const list = args.length ? PLAYERS.filter(p => args.includes(p.name)) : PLAYERS;
for (const a of args)
	if (!PLAYERS.some(p => p.name === a))
	{
		console.error(`Unknown player: ${a} (available: ${PLAYERS.map(p => p.name).join(', ')})`);
		process.exit(1);
	}

fs.mkdirSync(OUT, { recursive: true });
let errors = 0;
for (const p of list)
{
	process.stdout.write(`Generate ${p.name}... `);
	try { generate(p); console.log('OK'); }
	catch (e) { console.log('FAILED'); console.error(e.message); errors++; }
}
process.exit(errors ? 1 : 0);
